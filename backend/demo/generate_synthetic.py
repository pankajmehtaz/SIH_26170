"""
Synthetic data generator for burn-in screening demo.

IMPORTANT: All data generated by this script is SYNTHETIC / DEMO DATA.
It does NOT represent actual ISRO engineering data, thresholds, or limits.
Synthetic thresholds are chosen for demonstration purposes only.

Population structure:
  - ~85% healthy: tight distribution, mild natural drift
  - ~10% subtle anomalies: within abs_max but statistically unusual
  - ~3% obvious failures: exceed abs_max
  - ~7% drift defects: normal early readings but accelerating drift

Some components may belong to multiple anomaly categories.
"""

import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd

# Add parent directory to path for imports
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))


# ---------------------------------------------------------------------------
# Parameter definitions (SYNTHETIC — not real ISRO specs)
# ---------------------------------------------------------------------------
PARAMETERS = {
    "Iddq": {
        "unit": "µA",
        "abs_max": 50.0,
        "healthy_mean_0h": 10.0,
        "healthy_std_0h": 1.5,
        "natural_drift_per_h": 0.005,   # µA per hour
        "drift_noise_std": 0.3,
    },
    "Leakage_Current": {
        "unit": "µA",
        "abs_max": 100.0,
        "healthy_mean_0h": 20.0,
        "healthy_std_0h": 3.0,
        "natural_drift_per_h": 0.008,
        "drift_noise_std": 0.5,
    },
    "Prop_Delay": {
        "unit": "ns",
        "abs_max": 25.0,
        "healthy_mean_0h": 8.0,
        "healthy_std_0h": 0.8,
        "natural_drift_per_h": 0.002,
        "drift_noise_std": 0.15,
    },
    "Vout": {
        "unit": "mV",
        "abs_max": 3500.0,
        "healthy_mean_0h": 3300.0,
        "healthy_std_0h": 20.0,
        "natural_drift_per_h": -0.03,   # slight downward drift is normal
        "drift_noise_std": 3.0,
    },
}

TIMEPOINTS = [0, 24, 96, 168]
N_COMPONENTS = 200
BATCH_ID = "BATCH-DEMO-001"
RANDOM_SEED = 42


def generate_healthy_component(
    param_name: str, param_cfg: dict, rng: np.random.Generator
) -> dict:
    """Generate measurements for a healthy component."""
    value_0h = rng.normal(param_cfg["healthy_mean_0h"], param_cfg["healthy_std_0h"])
    # Ensure positive values (except Vout which can be large)
    value_0h = max(value_0h, 0.1)

    values = [value_0h]
    for i in range(1, len(TIMEPOINTS)):
        dt = TIMEPOINTS[i] - TIMEPOINTS[i - 1]
        drift = param_cfg["natural_drift_per_h"] * dt
        noise = rng.normal(0, param_cfg["drift_noise_std"])
        values.append(max(values[-1] + drift + noise, 0.1))

    return {
        "Value_0h": round(values[0], 4),
        "Value_24h": round(values[1], 4),
        "Value_96h": round(values[2], 4),
        "Value_168h": round(values[3], 4),
        "True_Label": "HEALTHY",
    }


def generate_subtle_anomaly(
    param_name: str, param_cfg: dict, rng: np.random.Generator
) -> dict:
    """
    Generate a component that is within abs_max but statistically unusual.
    Example from problem statement: most at 9–13 µA, this one at 45 µA (limit 50).
    """
    # Start at 3–5 sigma above healthy mean
    sigma_mult = rng.uniform(3.0, 5.0)
    value_0h = param_cfg["healthy_mean_0h"] + sigma_mult * param_cfg["healthy_std_0h"]
    # Ensure it stays below abs_max
    value_0h = min(value_0h, param_cfg["abs_max"] * 0.85)
    value_0h = max(value_0h, 0.1)

    # For Vout (where lower is worse), flip logic
    if param_cfg["natural_drift_per_h"] < 0:
        value_0h = param_cfg["healthy_mean_0h"] - sigma_mult * param_cfg["healthy_std_0h"]
        value_0h = max(value_0h, param_cfg["abs_max"] * 0.85)  # abs_max is upper for Vout

    values = [value_0h]
    for i in range(1, len(TIMEPOINTS)):
        dt = TIMEPOINTS[i] - TIMEPOINTS[i - 1]
        drift = param_cfg["natural_drift_per_h"] * dt * rng.uniform(1.0, 1.5)
        noise = rng.normal(0, param_cfg["drift_noise_std"] * 1.5)
        values.append(max(values[-1] + drift + noise, 0.1))

    return {
        "Value_0h": round(values[0], 4),
        "Value_24h": round(values[1], 4),
        "Value_96h": round(values[2], 4),
        "Value_168h": round(values[3], 4),
        "True_Label": "ANOMALY_SUBTLE",
    }


def generate_obvious_failure(
    param_name: str, param_cfg: dict, rng: np.random.Generator
) -> dict:
    """Generate a component that clearly exceeds abs_max by 168h."""
    value_0h = param_cfg["healthy_mean_0h"] + rng.uniform(2, 4) * param_cfg["healthy_std_0h"]
    value_0h = max(value_0h, 0.1)

    # For Vout, an obvious failure means value drops significantly
    if param_cfg["natural_drift_per_h"] < 0:
        value_0h = param_cfg["healthy_mean_0h"] - rng.uniform(2, 4) * param_cfg["healthy_std_0h"]

    values = [value_0h]
    for i in range(1, len(TIMEPOINTS)):
        dt = TIMEPOINTS[i] - TIMEPOINTS[i - 1]
        # Aggressive drift toward (or beyond) the limit
        drift = param_cfg["natural_drift_per_h"] * dt * rng.uniform(5.0, 10.0)
        noise = rng.normal(0, param_cfg["drift_noise_std"] * 2)
        values.append(max(values[-1] + drift + noise, 0.1))

    # Ensure 168h value exceeds abs_max for non-Vout parameters
    if param_cfg["natural_drift_per_h"] >= 0:
        values[-1] = max(values[-1], param_cfg["abs_max"] * rng.uniform(1.05, 1.3))

    return {
        "Value_0h": round(values[0], 4),
        "Value_24h": round(values[1], 4),
        "Value_96h": round(values[2], 4),
        "Value_168h": round(values[3], 4),
        "True_Label": "FAILURE_OBVIOUS",
    }


def generate_drift_defect(
    param_name: str, param_cfg: dict, rng: np.random.Generator
) -> dict:
    """
    Generate a component with normal early readings but accelerating drift.
    The 0h and 24h values look healthy; by 168h the value approaches the limit.
    """
    # Normal start
    value_0h = rng.normal(param_cfg["healthy_mean_0h"], param_cfg["healthy_std_0h"])
    value_0h = max(value_0h, 0.1)

    values = [value_0h]
    for i in range(1, len(TIMEPOINTS)):
        dt = TIMEPOINTS[i] - TIMEPOINTS[i - 1]
        # Drift accelerates with time (quadratic-ish)
        time_factor = (TIMEPOINTS[i] / 168.0) ** 2
        base_drift = param_cfg["natural_drift_per_h"] * dt
        accel_drift = base_drift * (1 + 8 * time_factor)
        noise = rng.normal(0, param_cfg["drift_noise_std"])
        values.append(max(values[-1] + accel_drift + noise, 0.1))

    # Ensure 168h value is near (70–95%) of abs_max but not necessarily over
    if param_cfg["natural_drift_per_h"] >= 0:
        target = param_cfg["abs_max"] * rng.uniform(0.70, 0.95)
        values[-1] = max(values[-1], target)

    return {
        "Value_0h": round(values[0], 4),
        "Value_24h": round(values[1], 4),
        "Value_96h": round(values[2], 4),
        "Value_168h": round(values[3], 4),
        "True_Label": "DRIFT_DEFECT",
    }


def generate_batch() -> pd.DataFrame:
    """Generate a full batch of synthetic screening data."""
    rng = np.random.default_rng(RANDOM_SEED)

    # Assign component types
    n_healthy = int(N_COMPONENTS * 0.80)
    n_subtle = int(N_COMPONENTS * 0.10)
    n_failure = int(N_COMPONENTS * 0.03)
    n_drift = N_COMPONENTS - n_healthy - n_subtle - n_failure

    component_types = (
        ["healthy"] * n_healthy
        + ["subtle_anomaly"] * n_subtle
        + ["obvious_failure"] * n_failure
        + ["drift_defect"] * n_drift
    )
    rng.shuffle(component_types)

    generators = {
        "healthy": generate_healthy_component,
        "subtle_anomaly": generate_subtle_anomaly,
        "obvious_failure": generate_obvious_failure,
        "drift_defect": generate_drift_defect,
    }

    rows = []
    for idx, comp_type in enumerate(component_types):
        comp_id = f"COMP-{idx + 1:04d}"

        for param_name, param_cfg in PARAMETERS.items():
            gen = generators[comp_type]
            data = gen(param_name, param_cfg, rng)

            rows.append({
                "Component_ID": comp_id,
                "Batch_ID": BATCH_ID,
                "Parameter": param_name,
                "Unit": param_cfg["unit"],
                "Abs_Max": param_cfg["abs_max"],
                **data,
            })

    df = pd.DataFrame(rows)

    # Create a Status column that simulates traditional static screening
    # (only catches obvious failures exceeding abs_max at 168h)
    def static_screen(row):
        if row["Parameter"] == "Vout":
            # For Vout, failure = value too low (but we store abs_max as upper)
            return "PASS"  # Simplified for demo
        return "FAIL" if row["Value_168h"] > row["Abs_Max"] else "PASS"

    df["Status"] = df.apply(static_screen, axis=1)

    return df


def save_demo_data():
    """Generate and save synthetic demo data."""
    output_dir = Path(__file__).resolve().parent / "synthetic_data"
    output_dir.mkdir(parents=True, exist_ok=True)

    df = generate_batch()

    # Save full dataset (with True_Label for evaluation)
    full_path = output_dir / "demo_batch_full.csv"
    df.to_csv(full_path, index=False)
    print(f"[SYNTHETIC DATA] Full dataset saved: {full_path} ({len(df)} rows)")

    # Save screening dataset (without True_Label — what the user would upload)
    screening_df = df.drop(columns=["True_Label"])
    screening_path = output_dir / "demo_batch_screening.csv"
    screening_df.to_csv(screening_path, index=False)
    print(f"[SYNTHETIC DATA] Screening dataset saved: {screening_path} ({len(screening_df)} rows)")

    # Save ground truth labels separately
    labels_df = df[["Component_ID", "Parameter", "True_Label"]].copy()
    labels_path = output_dir / "demo_batch_labels.csv"
    labels_df.to_csv(labels_path, index=False)
    print(f"[SYNTHETIC DATA] Labels saved: {labels_path}")

    print(f"\nBatch: {BATCH_ID}")
    print(f"Components: {df['Component_ID'].nunique()}")
    print(f"Parameters: {df['Parameter'].nunique()}")
    print(f"Label distribution:")
    print(df.groupby("True_Label")["Component_ID"].nunique().to_string())

    return df


if __name__ == "__main__":
    save_demo_data()
