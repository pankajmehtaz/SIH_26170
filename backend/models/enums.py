"""
Pydantic enums for risk levels, component status, defect archetypes, and validation issues.
"""

from enum import Enum


class RiskLevel(str, Enum):
    NORMAL = "NORMAL"
    MONITOR = "MONITOR"
    WARNING = "WARNING"
    CRITICAL = "CRITICAL"


class ComponentStatus(str, Enum):
    PASS = "PASS"
    FAIL = "FAIL"
    SUSPECT = "SUSPECT"
    UNKNOWN = "UNKNOWN"


class AnalysisState(str, Enum):
    PENDING = "PENDING"
    RUNNING = "RUNNING"
    COMPLETED = "COMPLETED"
    ERROR = "ERROR"


class DefectType(str, Enum):
    HEALTHY = "HEALTHY"
    POPULATION_OUTLIER = "POPULATION_OUTLIER"
    MILD_DRIFT = "MILD_DRIFT"
    STRONG_DRIFT = "STRONG_DRIFT"
    ACCELERATING_DRIFT = "ACCELERATING_DRIFT"
    EARLY_DRIFT = "EARLY_DRIFT"
    LATE_DRIFT = "LATE_DRIFT"
    STATIC_LIMIT_VIOLATION = "STATIC_LIMIT_VIOLATION"
    NOISY_MEASUREMENT = "NOISY_MEASUREMENT"
    UNKNOWN = "UNKNOWN"


class ValidationIssueType(str, Enum):
    MISSING_COLUMN = "MISSING_COLUMN"
    INVALID_FILE = "INVALID_FILE"
    INVALID_DATA_TYPE = "INVALID_DATA_TYPE"
    MISSING_VALUE = "MISSING_VALUE"
    DUPLICATE_COMPONENT = "DUPLICATE_COMPONENT"
    INVALID_NUMERICAL_VALUE = "INVALID_NUMERICAL_VALUE"
    INVALID_CHECKPOINT = "INVALID_CHECKPOINT"
    INCONSISTENT_UNITS = "INCONSISTENT_UNITS"
    INVALID_SPECIFICATION = "INVALID_SPECIFICATION"
    INCONSISTENT_SPECIFICATION = "INCONSISTENT_SPECIFICATION"
